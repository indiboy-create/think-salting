<?php

return [
    /*
    |--------------------------------------------------------------------------
    | 加密前缀
    |--------------------------------------------------------------------------
    | 参与 AdminPassword 哈希计算的自定义字符串，对应原始算法中的 Y!o^U。
    | 一旦线上已有密码入库，请勿随意修改；修改后历史密码将无法通过校验。
    */
    'prefix'         => 'Y!o^U',

    /*
    |--------------------------------------------------------------------------
    | 加密后缀
    |--------------------------------------------------------------------------
    | 参与 AdminPassword 哈希计算的自定义字符串，对应原始算法中的 V,is*Io(N。
    | 与 prefix 相同，线上运行后不建议变更。
    */
    'suffix'         => 'V,is*Io(N',

    /*
    |--------------------------------------------------------------------------

    | 随机盐字符池
    |--------------------------------------------------------------------------
    | make_salt 从该字符池中逐位随机取值，默认包含小写字母、大写字母、
    | 数字和常用符号。字符池内容可自由增删，但不要包含空格等不可见字符；
    | 支持 UTF-8 字符，每个字符按“一位”计算。
    */
    'charset'        => 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*()-_=+[]{};:,.<>?/~|',

    /*
    |--------------------------------------------------------------------------
    | 默认盐长度
    |--------------------------------------------------------------------------
    | 调用 make_salt() / Salting::makeSalt() 未传入位数时使用的默认长度。
    | 该长度同时作为 makePair() 生成第一段盐（salt）的默认长度。
    */
    'length'         => 8,

    /*
    |--------------------------------------------------------------------------
    | 第二段盐默认长度
    |--------------------------------------------------------------------------
    | makePair() 生成第二段盐（salt2）时使用的默认长度，可与 length 不同。
    */
    'length2'        => 10,

    /*
    |--------------------------------------------------------------------------
    | 数据库存储说明
    |--------------------------------------------------------------------------
    | 组件本身不直接连接数据库。约定业务表中保存两段盐的字段名为 salt、
    | salt2：注册时调用 Salting::makePair() 生成并保存到用户记录，登录时
    | 从数据库读取该用户的 salt、salt2，再调用 admin_password() 校验。
    | 下方字段名仅作为业务层约定参考，可按实际表结构调整。
    */
    'salt_field'     => 'salt',
    'salt2_field'    => 'salt2',
];